export const TRANSLATIONS: Readonly<Record<Locale, TranslationCatalog>> = {
  en,
  de,
  ja,
  tr,
  es,
  fr,
  "zh-Hans": zhHans,
  "zh-Hant": zhHant,
};

const EXACT_LOCALES = new Map<string, Locale>(
  SUPPORTED_LOCALES.map((locale) => [locale.toLowerCase(), locale]),
);

function browserLanguages(): readonly string[] {
  if (typeof navigator === "undefined") return [];
  if (navigator.languages.length > 0) return navigator.languages;
  return navigator.language ? [navigator.language] : [];
}

/** Resolve a BCP 47 language tag to a supported locale. */
export function matchLocale(languageTag: string): Locale | undefined {
  const normalized = languageTag.trim().replaceAll("_", "-").toLowerCase();
  if (!normalized || normalized === "auto") return undefined;

  const exact = EXACT_LOCALES.get(normalized);
  if (exact) return exact;

  const parts = normalized.split("-");
  const base = parts[0];
  if (base === "zh") {
    const subtags = new Set(parts.slice(1));
    if (["hant", "tw", "hk", "mo"].some((tag) => subtags.has(tag))) return "zh-Hant";
    return "zh-Hans";
  }
  if (base === "en" || base === "de" || base === "ja" || base === "tr" || base === "es" || base === "fr") {
    return base;
  }
  return undefined;
}

export function getSavedLocale(): Locale | undefined {
  if (typeof localStorage === "undefined") return undefined;
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    return stored ? matchLocale(stored) : undefined;
  } catch {
    return undefined;
  }
}

export function setSavedLocale(locale: Locale | null): void {
  if (typeof localStorage === "undefined") return;
  try {
    if (locale === null) localStorage.removeItem(LOCALE_STORAGE_KEY);
    else localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // The app remains usable when local storage is unavailable.
  }
}

export interface DetectLocaleOptions {
  /** Explicitly provided saved value; omit to read localStorage. */
  saved?: string | null;
  /** Explicitly provided browser preference list; omit to read navigator.languages. */
  languages?: readonly string[];
}

/**
 * Select the UI locale in privacy-preserving order: saved choice, browser
 * preferences (exact match before base-language match), then English.
 */
export function detectLocale(options: DetectLocaleOptions = {}): Locale {
  const saved = options.saved === undefined ? getSavedLocale() : options.saved;
  if (saved) {
    const matchedSaved = matchLocale(saved);
    if (matchedSaved) return matchedSaved;
  }

  const languages = options.languages ?? browserLanguages();
  for (const language of languages) {
    const matched = matchLocale(language);
    if (matched) return matched;
  }
  return DEFAULT_LOCALE;
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const template = TRANSLATIONS[locale][key];
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/gu, (placeholder, name: string) => {
    const value = params[name];
    return value === undefined ? placeholder : String(value);
  });
}

export type Translator = (key: TranslationKey, params?: TranslationParams) => string;

export function createTranslator(locale: Locale): Translator {
  return (key, params) => translate(locale, key, params);
}
